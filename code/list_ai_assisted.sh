def existed_at_base(p):
    return subprocess.run(["git", "cat-file", "-e", f"{BASE}:{p}"],
                          capture_output=True).returncode == 0


def docline(p):
    """First sentence of a python module docstring, which states what the file
    is. Read from the file rather than recalled."""
    try:
        src = open(p, encoding="utf-8").read()
    except OSError:
        return None
    # [^\n]* for the shebang, not .*: re.S makes . match newlines, and a
    # greedy .* walks past the real docstring to some later triple quote.
    # The optional [rRbBuUfF] prefix matters: r44_escape_scan.py must use a raw
    # docstring, because its text contains literal backslash-r and backslash-n
    # sequences. Without the prefix here the guard reports it as undocumented.
    m = re.search(r'^\s*(?:#![^\n]*\n)?[rRbBuUfF]{0,2}(?:"""|\'\'\')(.*?)(?:"""|\'\'\')',
                  src, re.S)
    if not m:
        return None
    body = m.group(1).strip()
    first = body.split("\n\n")[0].replace("\n", " ").strip()
    first = re.sub(r"\s+", " ", first)
    # one line means one sentence; the rest of the docstring is the file's own
    sent = re.split(r"(?<=[a-z0-9\)])\.\s+", first)[0]
    return sent.rstrip(".") or None


def esc(s):
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_")
             .replace("&", r"\&").replace("%", r"\%").replace("#", r"\#"))


