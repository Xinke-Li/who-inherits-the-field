#!/usr/bin/env bash
# Emit the LaTeX rows of Appendix "AI Tool Use" from the repository's own git
# history, so the disclosure table is regenerable rather than remembered.
#
#   bash code/list_ai_assisted.sh              # print the rows
#   bash code/list_ai_assisted.sh --list       # print path/status/source, no LaTeX
#
# MEMBERSHIP AND STATUS COME FROM GIT, NOT FROM A LIST KEPT BY HAND.
# A file is in the table if it differs from BASE, whether that difference is
# committed or still in the working tree, and it is "new" exactly when it did
# not exist at BASE.
#
# BASE is the last commit before the revision round. 713bfd3 is the first
# commit that creates results/revision/ and its own message opens the round, so
# its parent is the boundary. Commits before BASE built the original pipeline
# and had no AI involvement; widen BASE only if that stops being true.
BASE="${AI_DISCLOSURE_BASE:-9cbbbed}"
DIRS=(code colab reproduction)

set -u
cd "$(dirname "$0")/.."

if ! git rev-parse --verify --quiet "$BASE^{commit}" >/dev/null; then
  echo "list_ai_assisted: BASE $BASE is not a commit in this repository" >&2
  exit 2
fi

# committed since BASE, uncommitted against HEAD, and never-added files
{
  git diff --name-only "$BASE" HEAD -- "${DIRS[@]}"
  git diff --name-only HEAD -- "${DIRS[@]}"
  git ls-files --others --exclude-standard -- "${DIRS[@]}"
} | sed 's#\\#/#g' | sort -u | grep -vE '(^|/)(__pycache__|\.ipynb_checkpoints)/' \
  | grep -vE '\.(pyc|zip)$' > /tmp/.ai_paths.$$

BASE="$BASE" LISTONLY="${1:-}" python - /tmp/.ai_paths.$$ <<'PY'
